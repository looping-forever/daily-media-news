/**
 * functions/_middleware.js
 *
 * The digest archive is PUBLIC by design and this file sends no credential
 * prompt: it was a Basic-auth gate until 2026-10-30, when the gate was removed
 * because the owner could not open the site from a phone's in-app browser.
 *
 * It now answers ONE question itself. Pages serves the archive index with
 * HTTP 200 for a path that does not exist, so `/digests/2026-10-31-evening`
 * before that edition published was indistinguishable from a published one at
 * the status line. A monitoring arm reading `status == 200` was therefore
 * false-green on exactly the failure it exists to catch. Every request under
 * /digests/ whose answer is the index fallback now gets a real 404 instead.
 *
 * Everything else -- the index, assets, the 308 Pages issues from an existing
 * page's `.html` form to its extensionless form -- is returned untouched.
 */
const DIGEST_PREFIX = "/digests";

// The archive index's own <title>, read from the committed docs/index.html and
// generated by scripts/render_digest.py. A 200 whose body carries it is the
// not-found fallback, not a page; a rendered digest never carries it.
const INDEX_TITLE = "<title>Personal News Informer — Digest Archive</title>";

// Bodies larger than this are not the index fallback, so they are not read.
const MAX_INSPECT_BYTES = 2000000;

const NOT_FOUND_HTML = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <meta name="robots" content="noindex">
  <title>No edition for this slot</title>
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body {
      font-family: 'Inter', -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
      background: #0E1014;
      color: #ECEEF2;
      line-height: 1.6;
      min-height: 100vh;
      -webkit-text-size-adjust: 100%;
    }
    .wrap { max-width: 390px; margin: 0 auto; padding: 56px 20px; }
    .eyebrow {
      font-size: 11px;
      font-weight: 600;
      letter-spacing: .08em;
      text-transform: uppercase;
      color: #8A919F;
    }
    h1 { font-size: 22px; line-height: 1.35; margin: 10px 0 12px; }
    p { font-size: 14px; color: #A9B0BD; }
    a {
      display: inline-block;
      margin-top: 24px;
      font-size: 14px;
      font-weight: 600;
      color: #ECEEF2;
      text-decoration: none;
      border-bottom: 1px solid #272B34;
      padding-bottom: 2px;
    }
  </style>
</head>
<body>
  <main class="wrap">
    <p class="eyebrow">404</p>
    <h1>No edition for this slot</h1>
    <p>Nothing was published at this address. The archive lists only the
    editions that actually went out.</p>
    <a href="/">Open the digest archive</a>
  </main>
</body>
</html>
`;

function isDigestPath(pathname) {
  return pathname === DIGEST_PREFIX || pathname.startsWith(DIGEST_PREFIX + "/");
}

function notFoundResponse() {
  return new Response(NOT_FOUND_HTML, {
    status: 404,
    headers: {
      "Content-Type": "text/html; charset=utf-8",
      // no-store, not a short max-age: a cached 404 would keep hiding a slot
      // that publishes successfully minutes later.
      "Cache-Control": "no-store",
      "X-Content-Type-Options": "nosniff",
    },
  });
}

// A 200 that is the index fallback: HTML whose body is the archive index.
async function isIndexFallback(response) {
  const type = (response.headers.get("Content-Type") || "").toLowerCase();
  if (!type.includes("text/html")) return false;
  const length = Number(response.headers.get("Content-Length"));
  if (Number.isFinite(length) && length > MAX_INSPECT_BYTES) return false;
  return (await response.clone().text()).includes(INDEX_TITLE);
}

// A HEAD carries no body to judge, so the same path is asked for with GET.
// Both possible ASSETS behaviours end up correct: the index fallback is
// recognised by its body, and a plain 404 means the file does not exist.
async function headIsMissing(context) {
  const assets = context.env && context.env.ASSETS;
  if (!assets || typeof assets.fetch !== "function") return false;
  try {
    const probe = new Request(context.request.url, {
      method: "GET",
      headers: context.request.headers,
    });
    const response = await assets.fetch(probe);
    if (response.status === 404) return true;
    if (response.status !== 200) return false;
    return await isIndexFallback(response);
  } catch (error) {
    // An unanswerable probe leaves the response as Pages made it; a 500 here
    // would be worse than the status this path was asked to improve.
    return false;
  }
}

export async function onRequest(context) {
  const url = new URL(context.request.url);
  if (!isDigestPath(url.pathname)) return context.next();

  const response = await context.next();

  // A 404 is already the right answer, but Pages' own body is unrelated to the
  // digest; the slot page says what happened.
  if (response.status === 404) return notFoundResponse();
  // 308 from `.html` to the extensionless form, and every other non-200.
  if (response.status !== 200) return response;
  if (context.request.method === "HEAD") {
    return (await headIsMissing(context)) ? notFoundResponse() : response;
  }
  if (context.request.method !== "GET") return response;

  if (await isIndexFallback(response)) return notFoundResponse();
  return response;
}
