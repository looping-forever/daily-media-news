#!/usr/bin/env python3
"""check_public_sanitisation.py -- fail if a private value reached the public tree.

WHY THIS FILE EXISTS
--------------------
On 2026-10-25 the public Worker was regenerated by copying the private file over
it by hand. Nothing in the suite noticed until the Worker's own harness compared
origins, and the four failures that followed were about a Pages domain, not about
the district names that had also been published. A gate that only looks at the
Worker would have missed the rest of the tree, so this looks at all of it.

WHY IT HOLDS HASHES AND NOT THE VALUES
--------------------------------------
The first version of this gate stored the vocabulary base64-encoded, and lived
in this tree. That was wrong twice over: base64 is reversible in one line, and it
was committed, so the map was published in an encoding anyone decodes. The map
now lives only in the private working copy (`<private>/tools/publicise.py`); this
file holds SHA-256 fingerprints and can check a file without ever knowing what it
is looking for.

WHAT THAT DOES AND DOES NOT BUY, STATED HONESTLY
------------------------------------------------
It stops the repository from spelling the vocabulary out, and it stops this file
from being the thing that leaks it. It is NOT secrecy: a fingerprint of a short,
guessable word is recoverable by hashing a wordlist of town names, and any
committed fingerprint shares that weakness. Closing it completely means the
vocabulary lives in a CI secret and the gate fails closed when it is absent --
not done here, because it would make every local run and every fork PR unable to
check anything. This is the honest middle: no plaintext, no stored encoding, and
no false claim that a hash is a secret.

HOW IT MATCHES, AND WHY THAT KILLS THE FALSE POSITIVES
------------------------------------------------------
Every scanned line is split into maximal alphanumeric runs, so an
underscore-joined identifier, a dotted hostname and a path all yield their
components, and each component is lowercased and hashed. A hash is either in the
set or it is not, so:

  * `administrator` is one run and hashes to something not in the set -- the
    substring matching that produced 139 bogus hits on the first attempt cannot
    happen, because there is no substring matching.
  * a base64 image payload yields one long run rather than the short component
    buried inside it, so a committed fixture image does not turn the gate red.
  * the limit of the same choice: a value glued into a longer run is not caught.
    The alternative is substring matching, which is what made the gate unusable.

This paragraph used to spell the examples out. It could not: the gate scans this
file too, and the first run of the rewritten gate failed on its own docstring --
twice. That is the gate working, and it is why the prose here describes shapes
instead of quoting them.

WHAT IT SCANS
-------------
Files that would be published: tracked, plus untracked and not ignored. Only
committed content can be published, but a newly added file is not in the index
yet and is exactly the file a leak would be sitting in, so it is checked before
the commit rather than after. Binaries, VCS metadata and `.pen` design documents
are skipped.

USAGE
-----
    python scripts/check_public_sanitisation.py
    python scripts/check_public_sanitisation.py --root C:\\some\\copy
    python scripts/check_public_sanitisation.py --quiet

Exit codes: 0 clean, 1 a fingerprint matched (path:line and the hash are printed,
never the value), 2 the vocabulary is unusable.
"""

import argparse
import hashlib
import os
import re
import subprocess
import sys

SCRIPTS_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPTS_DIR)

#: SHA-256 of each vocabulary token, lowercased, sorted. No token appears here in
#: any recoverable-by-inspection form, and no encoding of one is stored either.
#: Generated from the private map; regenerate it there, never from this file.
VOCABULARY_SHA256 = (
    "1b29226934e647c506c97b905f5a02a85a51bf786a0c72cd601765e0e3d2ff2d",
    "54e4a5e4bab5a4de087e7905bbc2e60331e9ca548c175b2c2be69fa280eea988",
    "6e1e44f7cd17203b7dfaa85a28abcd5b0dfe6064b243fb26cb5ef622bd4cf269",
    "803b1d947f50a926d8edb46134b5c3c52fbb49e48653ef78688bab756861f573",
    "93df9019bbeede01bd7ef25531cdf9359f3e319ead10c2e77e14ebe246077f25",
    "bede073e92ac1ed30b52a0d0df01d6184146c620f3cd02acfd9173ed746199b5",
    "c16e389716b8165ba07f187308879df366d2b93e6aa7e9b15c9c0f443ec94df9",
    "e96c7b1ef7bb485e2f97da16fbd3861af4efe81ae981d05cead3f82577d64e6a",
    "f7ca0b531e7d38079e6d1f798e18e0d9b6ec584ede342702b6dbc56106dc3d28",
)

VOCABULARY_SET = frozenset(VOCABULARY_SHA256)

#: Maximal alphanumeric run. Underscores, dots, dashes, slashes and colons all
#: separate runs, which isolates a hostname component into a run of its own and
#: keeps a base64 payload welded together as one long run.
TOKEN_RE = re.compile(r"[A-Za-z0-9]+")

SKIP_EXTENSIONS = {
    ".png", ".jpg", ".jpeg", ".gif", ".ico", ".webp", ".avif", ".bmp", ".tif",
    ".tiff", ".woff", ".woff2", ".ttf", ".otf", ".eot", ".pdf", ".zip", ".gz",
    ".tgz", ".bz2", ".xz", ".7z", ".mp3", ".mp4", ".m4a", ".wav", ".mov",
    ".webm", ".pyc", ".pyo", ".so", ".dll", ".exe", ".bin", ".class", ".jar",
    ".sqlite", ".db", ".a", ".lib", ".o", ".pen",
}
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".pytest_cache"}


def fingerprint(token):
    return hashlib.sha256(token.lower().encode("utf-8")).hexdigest()


def scan_text(text, vocabulary=None):
    """Yield (line_number, digest) for every run in `text` whose hash is known.

    `vocabulary` is resolved at call time, not bound as a default argument: a
    default captures the set at import, which makes the gate untestable with a
    synthetic vocabulary and hides a real mis-wiring behind an empty result.
    """
    vocabulary = VOCABULARY_SET if vocabulary is None else vocabulary
    for number, line in enumerate(text.split("\n"), 1):
        for match in TOKEN_RE.finditer(line):
            digest = fingerprint(match.group(0))
            if digest in vocabulary:
                yield number, digest


def published_files(root):
    """Files that would be published: tracked, plus untracked and not ignored."""
    try:
        result = subprocess.run(
            ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            cwd=root, capture_output=True, timeout=60)
        if result.returncode == 0 and result.stdout:
            names = [n for n in result.stdout.decode("utf-8", "replace").split("\0") if n]
            return sorted(set(names))
    except (OSError, subprocess.SubprocessError):
        pass
    walked = []
    for base, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for name in files:
            walked.append(os.path.relpath(os.path.join(base, name), root))
    return sorted(walked)


def is_text(path):
    if os.path.splitext(path)[1].lower() in SKIP_EXTENSIONS:
        return False
    try:
        with open(path, "rb") as handle:
            raw = handle.read()
    except OSError:
        return False
    if b"\x00" in raw:
        return False
    try:
        raw.decode("utf-8")
    except UnicodeDecodeError:
        return False
    return True


def scan_tree(root, vocabulary=None):
    """Yield (relative_path, line_number, digest) for the whole tree."""
    vocabulary = VOCABULARY_SET if vocabulary is None else vocabulary
    for rel in published_files(root):
        path = os.path.join(root, rel)
        if not os.path.isfile(path) or not is_text(path):
            continue
        try:
            with open(path, "rb") as handle:
                text = handle.read().decode("utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        for number, digest in scan_text(text, vocabulary):
            yield rel.replace(os.sep, "/"), number, digest


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=REPO_ROOT,
                        help="tree to scan (default: this repository)")
    parser.add_argument("--quiet", action="store_true",
                        help="print only problems and the summary line")
    args = parser.parse_args(argv)

    if not VOCABULARY_SET:
        print("SANITISATION GATE CANNOT RUN: the vocabulary is empty", file=sys.stderr)
        return 2
    if any(not re.fullmatch(r"[0-9a-f]{64}", entry) for entry in VOCABULARY_SHA256):
        print("SANITISATION GATE CANNOT RUN: the vocabulary is not a set of "
              "SHA-256 fingerprints", file=sys.stderr)
        return 2

    root = os.path.abspath(args.root)
    findings = list(scan_tree(root))
    scanned = sum(1 for rel in published_files(root)
                  if os.path.isfile(os.path.join(root, rel))
                  and is_text(os.path.join(root, rel)))

    if findings:
        print("PUBLIC SANITISATION FAILED: %d match(es) in %d scanned file(s)"
              % (len(findings), scanned))
        for rel, number, digest in findings:
            # The value is deliberately absent: this output lands in CI logs.
            print("  %s:%d  sha256=%s" % (rel, number, digest))
        print("\nRegenerate the file with the private sanitiser "
              "(<private>/tools/publicise.py); do not patch it here.")
        return 1

    if not args.quiet:
        print("public sanitisation clean: %d file(s) scanned against %d "
              "fingerprint(s)" % (scanned, len(VOCABULARY_SET)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
